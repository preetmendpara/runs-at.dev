// Renders infra/cloud-init/ns1.yaml and ns2.yaml from infra/powerdns and
// infra/monitoring so the configs live in one place.
//   node infra/cloud-init/build.mjs          # write
//   node infra/cloud-init/build.mjs --check  # exit 1 if the yaml is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const src = (p) => readFileSync(join(here, '..', p), 'utf8');

const common = [
  ['powerdns/pdns-override.conf', '/etc/systemd/system/pdns.service.d/override.conf', '0644'],
  ['powerdns/pdns-backup.sh', '/usr/local/sbin/pdns-backup.sh', '0750'],
  ['monitoring/check-dns.sh', '/usr/local/sbin/check-dns.sh', '0755'],
  ['powerdns/pdns-cron', '/etc/cron.d/pdns-local', '0644'],
  ['powerdns/logrotate-pdns', '/etc/logrotate.d/pdns-local', '0644'],
  ['powerdns/unattended-upgrades', '/etc/apt/apt.conf.d/52unattended-upgrades-local', '0644'],
];

const roles = {
  ns1: {
    packages: ['pdns-server', 'pdns-backend-pgsql', 'postgresql', 'postgresql-client'],
    files: [['powerdns/pdns-primary.conf', '/etc/powerdns/pdns.conf', '0640'], ['powerdns/setup-primary.sh', '/usr/local/sbin/setup-pdns.sh', '0750'], ...common],
  },
  ns2: {
    packages: ['pdns-server', 'pdns-backend-sqlite3', 'sqlite3'],
    files: [['powerdns/pdns-secondary.conf', '/etc/powerdns/pdns.conf', '0640'], ['powerdns/setup-secondary.sh', '/usr/local/sbin/setup-pdns.sh', '0750'], ...common],
  },
};

export function render(role) {
  const { packages, files } = roles[role];
  const out = [
    '#cloud-config',
    `# ${role}.runs-at.dev - GENERATED by infra/cloud-init/build.mjs; edit infra/powerdns or infra/monitoring instead.`,
    '# Contains no secrets: setup-pdns.sh generates them on the host.',
    `hostname: ${role}`,
    'package_update: true',
    'package_upgrade: true',
    'packages:',
    ...['unattended-upgrades', 'bind9-dnsutils', 'openssl', ...packages].map((p) => `  - ${p}`),
    'write_files:',
  ];
  for (const [from, path, mode] of files) {
    out.push(`  - path: ${path}`, `    permissions: '${mode}'`, '    defer: true', '    content: |');
    for (const l of src(from).replace(/\n$/, '').split('\n')) out.push(l ? `      ${l}` : '');
  }
  out.push(
    'runcmd:',
    // Ubuntu's systemd-resolved stub listens on 127.0.0.53:53, which does not
    // clash with pdns on 0.0.0.0:53 on Linux, but free it to be safe.
    "  - [sh, -c, 'mkdir -p /etc/systemd/resolved.conf.d && printf \"[Resolve]\\nDNSStubListener=no\\n\" > /etc/systemd/resolved.conf.d/no-stub.conf && ln -sf /run/systemd/resolve/resolv.conf /etc/resolv.conf && systemctl restart systemd-resolved']",
    '  - [chown, root:pdns, /etc/powerdns/pdns.conf]',
    '  - [/usr/local/sbin/setup-pdns.sh]',
  );
  return out.join('\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  let stale = false;
  for (const role of Object.keys(roles)) {
    const file = join(here, `${role}.yaml`);
    const text = render(role);
    if (process.argv.includes('--check')) {
      let cur = '';
      try { cur = readFileSync(file, 'utf8'); } catch {}
      if (cur !== text) { console.error(`${file} is stale; run node infra/cloud-init/build.mjs`); stale = true; }
    } else writeFileSync(file, text);
  }
  process.exit(stale ? 1 : 0);
}
